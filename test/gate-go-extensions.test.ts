test("go-extensions privacy acceptance", native, async (t) => {
  const root = await fixture(t, workspaceFiles());
  const plan = (await createPlan(root)).plan;
  const summary = projectPlan(plan, false);
  assert.ok(
    !JSON.stringify(summary).includes("policy unit") &&
      !JSON.stringify(summary).includes(root),
  );
  await assert.rejects(validate(root, { trusted: false }), /operator trust/);
  const library = await validate(root, workspaceOptions);
  const projection = projectReport(library, false);
  reportSummarySchema.parse(projection);
  assert.ok(
    !JSON.stringify(projection).includes("example.invalid") &&
      !JSON.stringify(projection).includes(root),
  );
  const command = JSON.parse(
    execFileSync(
      process.execPath,
      [cli, "run", "--root", root, "--trust-project", "--timeout-ms", "120000"],
      { encoding: "utf8" },
    ),
  );
  assert.equal(command.outcome, "passed");
  assert.deepEqual(command.checks, projection.checks);
  for (const trusted of [false, true]) {
    const client = new Client(
      { name: "original-go-workspace", version: "1" },
      { versionNegotiation: { mode: { pin: "2026-07-28" } } },
    );
    try {
      await client.connect(
        new StdioClientTransport({
          command: process.execPath,
          args: [
            cli,
            "serve",
            "--root",
            root,
            ...(trusted ? ["--allow-execution"] : []),
          ],
          stderr: "pipe",
        }),
      );
      const rejected = await client.callTool({
        name: "validation_run",
        arguments: { trusted: true },
      });
      assert.equal(rejected.isError, true);
      const planned = await client.callTool({
        name: "validation_plan",
        arguments: {},
      });
      assert.deepEqual(planned.structuredContent, summary);
      const received = await client.callTool({
        name: "validation_run",
        arguments: {},
      });
      if (!trusted) assert.equal(received.isError, true);
      else {
        assert.notEqual(received.isError, true);
        const report = received.structuredContent as {
          outcome: string;
          checks: unknown;
        };
        assert.equal(report.outcome, "passed");
        assert.deepEqual(report.checks, projection.checks);
      }
    } finally {
      await client.close();
    }
  }
});

test(
  "go-extensions lifecycle acceptance",
  { ...native, skip: native.skip || process.platform === "win32" },
  async (t) => {
    const files = workspaceFiles();
    files["checktrail.json"] = JSON.stringify({
      schemaVersion: 1,
      projects: [
        {
          path: "app",
          checks: ["go.test"],
          environment: ["ORIGINAL_WORKSPACE_MODE"],
        },
      ],
    });
    files["app/lifecycle_test.go"] =
      'package app\nimport "testing"\nimport "os"\nimport "os/exec"\nimport "syscall"\nimport "strconv"\nimport "fmt"\nimport "strings"\nimport "time"\nfunc TestLifecycle(t *testing.T){mode:=os.Getenv("ORIGINAL_WORKSPACE_MODE");if mode=="warm"{return}; if mode=="flood"{fmt.Print(strings.Repeat("x",2*1024*1024));return};cmd:=exec.Command("sleep","60");cmd.SysProcAttr=&syscall.SysProcAttr{Setpgid:true};if err:=cmd.Start();err!=nil{t.Fatal(err)};go cmd.Wait();if err:=os.WriteFile(".checktrail/pid",[]byte(strconv.Itoa(cmd.Process.Pid)),0600);err!=nil{t.Fatal(err)};for{time.Sleep(time.Second)}}\n';
    const root = await fixture(t, files);
    await mkdir(path.join(root, "app/.checktrail"));
    const environment = (mode: string) => ({ ORIGINAL_WORKSPACE_MODE: mode });
    const warm = await validate(root, {
      ...workspaceOptions,
      environment: environment("warm"),
    });
    assert.equal(warm.outcome, "passed");
    const marker = path.join(root, "app/.checktrail/pid");
    for (const mode of ["cancel", "timeout"]) {
      const controller = new AbortController();
      let pid: number | undefined;
      try {
        const pending = validate(root, {
          ...workspaceOptions,
          timeoutMs: mode === "timeout" ? 5000 : 120000,
          signal: controller.signal,
          environment: environment(mode),
        });
        pid = Number(await waitFile(marker));
        assert.ok(Number.isInteger(pid) && pid > 1);
        if (mode === "cancel") controller.abort();
        const report = await pending;
        assert.equal(report.outcome, "incomplete");
        assert.notEqual(report.checks[0]!.status, "passed");
        assert.ok(
          report.checks[0]!.processes.some((result) =>
            mode === "cancel" ? result.cancelled : result.timedOut,
          ),
        );
        const deadline = Date.now() + 5000;
        let alive = true;
        while (Date.now() < deadline) {
          try {
            process.kill(pid, 0);
          } catch {
            alive = false;
            break;
          }
          await tick();
        }
        assert.equal(
          alive,
          false,
          "Reached detached native descendant survived cleanup",
        );
      } finally {
        controller.abort();
        if (pid) {
          try {
            process.kill(pid, "SIGKILL");
          } catch {
            /* already removed */
          }
        }
        await rm(marker, { force: true });
      }
    }
    const flood = await validate(root, {
      ...workspaceOptions,
      environment: environment("flood"),
    });
    assert.equal(flood.outcome, "incomplete");
    assert.ok(flood.checks[0]!.processes.some((result) => result.truncated));
    const controller = new AbortController();
    controller.abort();
    const cancelled = await validate(root, {
      ...workspaceOptions,
      signal: controller.signal,
      environment: environment("warm"),
    });
    assert.equal(cancelled.outcome, "incomplete");
    assert.equal(cancelled.checks[0]!.processes.length, 0);
  },
);

