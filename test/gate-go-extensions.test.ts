test("go-extensions prerequisite acceptance", async (t) => {
  const root = await fixture(t, workspaceFiles());
  const valid = await readFile(path.join(root, "go.work"), "utf8");
  for (const text of [
    "go 1.23\nuse ../outside\n",
    "go 1.23\nuse /outside\n",
    "go 1.23\nuse (\n ./app\n ./app\n)\n",
    "go 1.23\nuse ./missing\n",
    'go 1.23\nuse (\n ./app\n "./policy unit"\n)\nreplace example.invalid/helper => /outside\n',
    'go 1.23\nuse (\n ./app\n "./policy unit"\n)\nunknown setting\n',
    "go 1.23\nuse (\n ./app\n",
    "go 1.23\nuse `./app`\n",
  ]) {
    await writeFile(path.join(root, "go.work"), text);
    const { plan } = await createPlan(root);
    assert.ok(plan.checks.every((check) => check.unavailableReason));
    const report = await validate(root, workspaceOptions);
    assert.equal(report.outcome, "incomplete");
    assert.ok(
      report.checks.every(
        (check) =>
          check.status === "unavailable" && check.processes.length === 0,
      ),
    );
  }
  await writeFile(path.join(root, "go.work"), valid);
  await rm(path.join(root, "helper unit/go.mod"));
  assert.ok(
    (await createPlan(root)).plan.checks.every(
      (check) => check.unavailableReason,
    ),
  );
  await writeFile(
    path.join(root, "helper unit/go.mod"),
    "module example.invalid/helper\ngo 1.23\n",
  );
  await symlink(path.join(root, "go.work"), path.join(root, "app/go.work"));
  assert.ok(
    (await createPlan(root)).plan.checks
      .filter((check) => check.project === "app")
      .every((check) => check.unavailableReason),
  );
  await rm(path.join(root, "app/go.work"));
  await mkdir(path.join(root, "tools"));
  await writeFile(
    path.join(root, "tools/go"),
    "#!/bin/sh\n: > executed\nexit 99\n",
  );
  await chmod(path.join(root, "tools/go"), 0o755);
  await writeFile(
    path.join(root, "checktrail.json"),
    workspaceConfiguration(["go.test"], ["PATH"]),
  );
  await createPlan(root, { environment: { PATH: path.join(root, "tools") } });
  await assert.rejects(readFile(path.join(root, "app/executed")), {
    code: "ENOENT",
  });
  await rm(path.join(root, "tools/go"));
  const absent = await validate(root, {
    ...workspaceOptions,
    environment: { PATH: path.join(root, "tools") },
  });
  assert.equal(absent.outcome, "incomplete");
  assert.ok(absent.checks.every((check) => check.status !== "passed"));
  const extra = Array.from({ length: 14 }, (_, index) => "extra" + index);
  for (const directory of extra) {
    await mkdir(path.join(root, directory));
    await writeFile(
      path.join(root, directory, "go.mod"),
      "module example.invalid/" + directory + "\ngo 1.23\n",
    );
  }
  await writeFile(path.join(root, "checktrail.json"), workspaceConfiguration());
  const bounded = (count: number) =>
    'go 1.23\nuse (\n ./app\n "./policy unit"\n' +
    extra
      .slice(0, count)
      .map((value) => " ./" + value + "\n")
      .join("") +
    ')\nreplace example.invalid/helper => "./helper unit"\n';
  await writeFile(path.join(root, "go.work"), bounded(13));
  assert.ok(
    (await createPlan(root)).plan.checks.every(
      (check) =>
        check.goWorkspace?.modules.length === 16 && !check.unavailableReason,
    ),
  );
  await writeFile(path.join(root, "go.work"), bounded(14));
  assert.ok(
    (await createPlan(root)).plan.checks.every((check) =>
      check.unavailableReason?.includes("sixteen"),
    ),
  );
});

